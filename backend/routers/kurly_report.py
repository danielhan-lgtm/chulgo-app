def kurly_label(key: str):
    """정규화 상품명(공백 제거·소문자)에서 키워드로 라벨 추정. 이미지 PDF OCR 오인식('표고버±것', '[ ]')을 흡수한다."""
    k = str(key or "")
    if "표고" in k or "머쉬룸" in k or "시타케" in k:
        return "스모크칠리" if ("스모크" in k or "칠리" in k) else "머쉬룸 오리지널"
    if "베지" in k:
        return "베지크리스프 핫앤스파이시" if ("핫" in k or "스파이시" in k) else "베지크리스프"
    if "브로콜" in k:
        return "브로콜리 플로렛"
    if "웨지" in k:
        return "포테이토 웨지 스위트칠리" if ("스위트" in k or "칠리" in k) else "포테이토 웨지"
    if "팝" in k or "아보카" in k:
        if "할라" in k:
            return "팝타임 42g 할라피뇨"
        if "스윗" in k or "솔티" in k:
            return "팝타임 42g 스윗앤솔티"
        if "체다" in k or "세다" in k:
            return "팝타임 28g 체다치즈"
        if "씨솔트" in k:
            return "팝타임 28g 씨솔트"
    if "프레첼" in k or "프레젤" in k:
        if "참깨" in k:
            return "프로틴 프레첼 참깨"
        if "에브리" in k:
            return "프로틴 프레첼 에브리띵"
        if "씨솔트" in k:
            return "프로틴 프레첼 씨솔트"
    if "멜라" in k:
        return "멜라토닌"
    if "731" in k:
        return "ERr731"
    return None


def kurly_barcode(key: str):
    lb = kurly_label(key)
    return LABEL_BARCODES.get(lb) if lb else None


